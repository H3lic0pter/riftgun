package dev.riftgun.network;

public enum PortalAction {
    OPEN_GUI,
    OPEN_MODULES,
    CREATE_CURRENT,
    CREATE_COORDINATE,
    EDIT_DESTINATION,
    SHARE_DESTINATION_CHAT,
    CREATE_COORDINATE_NOTE,
    DELETE_DESTINATION,
    TOGGLE_PIN,
    VIEW_DESTINATION,
    SELECT_DESTINATION,
    SELECT_EXTERNAL_DESTINATION,
    SELECT_PLAYER,
    OPEN_PORTAL,
    OPEN_EXTERNAL_DESTINATION,
    OPEN_RANDOM_RIFT,
    OPEN_SELECTED,
    OPEN_SELECTED_SURFACE_FACE,
    CLEAR_EXTERNAL_DESTINATION,
    RELOCATE_ENTITY,
    PLACE_PAIRING_ENDPOINT,
    TOGGLE_FUNCTION_MODE,
    CYCLE_PLACEMENT_MODE,
    OPEN_MODE_RADIAL,
    SET_RADIAL_MODE,
    ADJUST_SURFACE_RANGE,
    CREATE_GROUP,
    RENAME_GROUP,
    DELETE_GROUP,
    MOVE_GROUP,
    MOVE_DESTINATION_GROUP,
    SET_GROUP_EXPANDED,
    SET_SETTINGS,
    SET_GUN_MODULE_SETTINGS,
    TOGGLE_BUCKET_MODE,
    CLEAR_GUN_FLUID,
    REQUEST_PLAYERS,
    OPEN_PLAYER_PORTAL,
    TOGGLE_PLAYER_PIN,
    CLOSE_PORTALS,
    SET_PRIVACY,
    SET_PRIVACY_OVERRIDE,
    REQUEST_PRIVACY_PLAYERS;

    public boolean requiresPortalGun() {
        return switch (this) {
            case SHARE_DESTINATION_CHAT, CLOSE_PORTALS, SET_PRIVACY, SET_PRIVACY_OVERRIDE,
                 REQUEST_PRIVACY_PLAYERS -> false;
            default -> true;
        };
    }

    public boolean isExclusiveKeyboardShortcut() {
        return this == OPEN_SELECTED || this == OPEN_SELECTED_SURFACE_FACE
            || this == RELOCATE_ENTITY || this == PLACE_PAIRING_ENDPOINT
            || this == TOGGLE_FUNCTION_MODE || this == CYCLE_PLACEMENT_MODE
            || this == OPEN_MODE_RADIAL || this == SET_RADIAL_MODE
            || this == ADJUST_SURFACE_RANGE;
    }
}
